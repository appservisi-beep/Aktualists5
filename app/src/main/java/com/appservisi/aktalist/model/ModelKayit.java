package com.appservisi.aktalist.model;

public class ModelKayit {
    String kayitid;
    String resimbaslik;
    String marka;
    String resim;
    String gelenid;
    int resimsirasi;


    public String getKayitid() {
        return kayitid;
    }

    public void setKayitid(String kayitid) {
        this.kayitid = kayitid;
    }

    public String getResimbaslik() {
        return resimbaslik;
    }

    public void setResimbaslik(String resimbaslik) {
        this.resimbaslik = resimbaslik;
    }

    public String getMarka() {
        return marka;
    }

    public void setMarka(String marka) {
        this.marka = marka;
    }

    public String getResim() {
        return resim;
    }

    public void setResim(String resim) {
        this.resim = resim;
    }

    public String getGelenid() {
        return gelenid;
    }

    public void setGelenid(String gelenid) {
        this.gelenid = gelenid;
    }

    public int getResimsirasi() {
        return resimsirasi;
    }

    public void setResimsirasi(int resimsirasi) {
        this.resimsirasi = resimsirasi;
    }
}
